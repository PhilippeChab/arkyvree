import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

import { CodeFile } from "@/database/packages/dnd35-from-parser/tools/generator/code/CodeFile.ts";
import { type ImportTable } from "@/database/packages/dnd35-from-parser/tools/generator/code/imports.ts";
import { CORE_BOOK } from "@/database/packages/dnd35-from-parser/tools/references/files.ts";
import ReferenceLoader from "@/database/packages/dnd35-from-parser/tools/references/ReferenceLoader.ts";
import type { ItemSeed } from "@/database/packages/dnd35/content/items/types.ts";

/** What a generated file's opening comment says first. */
const GENERATED = "Auto-generated by the SRD pipeline (`bun run parser:generate`): do not edit it by hand.";

/** The files a book's items/ can hold, each with the list it exports, in the order the items' index lists them. */
const ITEM_FILES = [
  ["simpleWeapons.ts", "SIMPLE_WEAPONS"],
  ["martialWeapons.ts", "MARTIAL_WEAPONS"],
  ["exoticWeapons.ts", "EXOTIC_WEAPONS"],
  ["armor.ts", "ARMOR"],
  ["shields.ts", "SHIELDS"],
  ["goods.ts", "GOODS"],
  ["magicArmor.ts", "MAGIC_ARMOR"],
  ["magicShields.ts", "MAGIC_SHIELDS"],
  ["magicWeapons.ts", "MAGIC_WEAPONS"],
  ["wondrousItems.ts", "WONDROUS_ITEMS"],
  ["rings.ts", "RINGS"],
  ["rods.ts", "RODS"],
  ["staffs.ts", "STAFFS"],
];

/** The builders an item file can import, in the order its import lists them. */
const ITEM_IMPORTS: ImportTable = [
  [
    "@/database/packages/dnd35/content/items/proficiencies.ts",
    [
      "simple",
      "martial",
      "exotic",
      "HEAVY_ARMOR_PROF",
      "LIGHT_ARMOR_PROF",
      "MEDIUM_ARMOR_PROF",
      "SHIELD_PROF",
      "TOWER_SHIELD_PROF",
    ],
  ],
  [
    "@/database/packages/dnd35/content/items/properties.ts",
    ["weaponProperties", "armorProperties", "shieldProperties"],
  ],
];

/**
 * A generator's core, which its concerns (`concerns/`) build on: the folder it writes to (generated/, or a test's),
 * whether it logs what it does, and what several kinds of files are written with.
 */
export class BaseGenerator {
  constructor(
    readonly dir: string,
    readonly quiet: boolean,
  ) {}

  /**
   * Whether a book copies feats and spells from the core rules (cowFeats.ts, cowSpells.ts): an extension with classes.
   * The core rules are what extensions copy from.
   */
  protected copiesFromCore(book: string): boolean {
    return book !== CORE_BOOK && ReferenceLoader.loadClasses(book).length > 0;
  }

  /** Logs what the generator does, unless it's quiet. */
  protected log(message: string) {
    if (!this.quiet) console.log(message);
  }

  /**
   * Writes a generated file, creating its folder: its code under the opening comment every generated file has, which
   * lists what's left to review in it (`notes`, a class's).
   */
  protected write(path: string, code: string, notes: string[] = []) {
    const header =
      notes.length === 0
        ? [`/** ${GENERATED} */`]
        : ["/**", ` * ${GENERATED}`, " *", " * To review:", ...notes.map((note) => ` * - ${note}`), " */"];
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, [...header, "", code].join("\n"));
    this.log(`Generated: ${relative(this.dir, path)}`);
  }

  /** Writes a file of items, `constName`, with the builders an item's fields are written with (`ITEM_IMPORTS`). */
  protected writeItemFile(path: string, constName: string, items: ItemSeed[]) {
    const file = new CodeFile(ITEM_IMPORTS);
    file.list(
      constName,
      "ItemSeed",
      items.flatMap((item) => file.item(item)),
    );
    this.write(path, file.code());
  }

  /**
   * Writes a book's items' index (items/index.ts): every item file it has, mundane or magic, whichever reference was
   * generated last.
   */
  protected writeItemIndex(outDir: string) {
    const file = new CodeFile();
    file.lines.push(
      ...ITEM_FILES.filter(([name]) => existsSync(join(outDir, name))).map(
        ([name, list]) => `export { ${list} } from "./${name}";`,
      ),
      ``,
    );
    this.write(join(outDir, "index.ts"), file.code());
  }
}
